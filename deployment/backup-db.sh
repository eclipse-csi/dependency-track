# Dumps a Dependency-Track database with pg_dump, running in a temporary pod in
# the given namespace, so no local PostgreSQL tools or database access are needed.
#
# Parameters:
#   namespace    OpenShift namespace to run the temporary pod in
#   db-host      Database host, as reachable from that namespace
#   db-name      Name of the database to dump
#   db-user      Database user to connect as
#   secret-name  Secret in the namespace that holds the database password
#   secret-key   Key in that Secret that holds the database password

# Bash strict-mode
set -o errexit
set -o nounset
set -o pipefail

IFS=$'\n\t'

usage() {
  echo "Usage: $0 <namespace> <db-host> <db-name> <db-user> <secret-name> <secret-key>"
  exit 1
}

[[ $# -eq 6 ]] || usage
NAMESPACE="${1}"
DB_HOST="${2}"
DB_NAME="${3}"
DB_USER="${4}"
SECRET_NAME="${5}"
SECRET_KEY="${6}"

# Must be at least the server's major version
IMAGE="docker.io/library/postgres:18"
POD="pg-dump-$(date +%s)"
OUTPUT="dtrack-${NAMESPACE}-$(date +%F).dump"

if [[ -e "${OUTPUT}" ]]; then
  echo "ERROR: '${OUTPUT}' already exists"
  exit 1
fi

if [[ -z "$(oc get secret "${SECRET_NAME}" -n "${NAMESPACE}" \
    -o go-template="{{ if index .data \"${SECRET_KEY}\" }}found{{ end }}")" ]]; then
  echo "ERROR: Key '${SECRET_KEY}' not found in Secret '${SECRET_NAME}' in '${NAMESPACE}'"
  exit 1
fi

cleanup() {
  oc delete pod "${POD}" -n "${NAMESPACE}" --ignore-not-found --wait=false > /dev/null
}
trap cleanup EXIT

# The pod reads the password from the Secret, so it never leaves the cluster.
# The overrides replace the container generated by 'oc run'.
OVERRIDES="$(jq -n --arg pod "${POD}" --arg image "${IMAGE}" \
  --arg secret "${SECRET_NAME}" --arg key "${SECRET_KEY}" '{
    spec: {
      containers: [{
        name: $pod,
        image: $image,
        command: ["sleep", "3600"],
        env: [{name: "PGPASSWORD", valueFrom: {secretKeyRef: {name: $secret, key: $key}}}]
      }]
    }
  }')"

# The pod idles while pg_dump runs via 'oc exec': 'oc run -i' can lose the
# beginning of the output. The sleep limits its lifetime if cleanup fails.
oc run "${POD}" -n "${NAMESPACE}" --restart=Never --image="${IMAGE}" \
  --overrides="${OVERRIDES}" > /dev/null
oc wait "pod/${POD}" -n "${NAMESPACE}" --for=condition=Ready --timeout=120s > /dev/null

echo "Dumping ${DB_NAME}@${DB_HOST} to ${OUTPUT}"
if ! oc exec -n "${NAMESPACE}" "${POD}" -- \
    pg_dump -h "${DB_HOST}" -U "${DB_USER}" -d "${DB_NAME}" -Fc > "${OUTPUT}"; then
  rm -f "${OUTPUT}"
  echo "ERROR: pg_dump failed"
  exit 1
fi

if [[ "$(head -c 5 "${OUTPUT}")" != "PGDMP" ]]; then
  echo "ERROR: '${OUTPUT}' is not a valid dump"
  exit 1
fi

echo "Done: $(ls -lh "${OUTPUT}" | awk '{print $5}')"
